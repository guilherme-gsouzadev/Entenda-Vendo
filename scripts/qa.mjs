import fs from 'node:fs';
import {SHOTS,SCENE_TIMES} from '../src/data/timeline.mjs';
import {urns,probability} from '../src/data/math.mjs';
const code=fs.readFileSync(new URL('../src/scenes/Shots.tsx',import.meta.url),'utf8');
const artwork=fs.readFileSync(new URL('../src/components/Artwork.tsx',import.meta.url),'utf8');
const thumbnail=fs.readFileSync(new URL('../src/components/Thumbnail.tsx',import.meta.url),'utf8');
const checks=[
 ['Shot implementation exists for every planned shot',SHOTS.every(sh=>code.includes(`case '${sh.id}'`))],
 ['9 scenes + 17 shots declared',SCENE_TIMES.length===9&&SHOTS.length===17],
 ['Physical after-state derived from math object',code.includes('...urns.after')],
 ['Mathematical challenge derived from math object',code.includes('...urns.challenge')],
 ['All balls data-driven (not generated by an image model)',artwork.includes('positions.map')&&artwork.includes("i<blue?'blue':'red'")],
 ['Extracted blue ball is explicit separate vector',artwork.includes('showRemoved&&<Ball')],
 ['Thumbnail before/after use authoritative math state',thumbnail.includes('urns.before.blue')&&thumbnail.includes('urns.after.blue')],
 ['Physical complement has all three paths',code.includes('first="B" second="R"')&&code.includes('first="R" second="B"')&&code.includes('first="R" second="R"')],
 ['Final complement numerically correct',Math.abs(probability.challengeRed-5/7)<1e-12],
 ['Thumbnail preview exported',fs.existsSync(new URL('../assets/thumbnail_verified.png',import.meta.url))],
];
for(const [name,pass] of checks)console.log(`${pass?'PASS':'FAIL'} | ${name}`);
console.log(`${checks.filter(x=>x[1]).length}/${checks.length} static/integration-model checks passed; no runtime render validation claimed.`);
if(checks.some(x=>!x[1]))process.exitCode=1;
